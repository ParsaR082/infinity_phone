// Helper functions for formatting prices and currency in Persian
window.formatToman = function(amount) {
  if (typeof amount !== 'number') return amount;
  // Convert to Persian digits and add commas
  const persianDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  const formatted = amount.toLocaleString('en-US').replace(/\d/g, d => persianDigits[d]);
  return `${formatted} تومان`;
};

window.toPersianNumber = function(num) {
  if (num === null || num === undefined) return '';
  const persianDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return String(num).replace(/\d/g, d => persianDigits[d]);
};

